// Writes src/abi.js, the few ABI entries the vetoer needs, from the keeper's generated ABI.
// Run `npm run build` at the repository root first (it compiles src/abi.ts into dist/src/abi.js).
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const m = await import(pathToFileURL(join(here, "..", "..", "dist", "src", "abi.js")).href);
const pick = (abi, names) => abi.filter((x) => names.includes(x.name));
const receiver = pick(m.guardianReceiverAbi, ["VerdictProposed", "pendingVoid", "vetoVerdict", "vetoDelay", "vetoer"]);
const lens = pick(m.predictionMarketLensAbi, ["getRound", "getMarket"]);
let body = "// Generated by scripts/sync-abi.mjs from the keeper's ABI. Do not edit by hand.\n\n";
body += `export const receiverAbi = ${JSON.stringify(receiver, null, 2)};\n\n`;
body += `export const lensAbi = ${JSON.stringify(lens, null, 2)};\n`;
writeFileSync(join(here, "..", "src", "abi.js"), body);
console.log("wrote src/abi.js");
