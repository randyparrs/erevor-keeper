// Regenerates src/abi.ts with only the functions, events and errors the keeper uses, from the Foundry build output
// of the EREVOR contracts. Usage: node scripts/sync-abi.mjs <path to the EREVOR out/ folder>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = process.argv[2];
if (!out) throw new Error("usage: node scripts/sync-abi.mjs <EREVOR out/ folder>");

const pick = {
  predictionMarketAbi: {
    path: "PredictionMarket.sol/PredictionMarket.json",
    names: [
      "executeBoundary",
      "paused",
      "reader",
      "hasRole",
      "DEFAULT_ADMIN_ROLE",
      "PAUSER_ROLE",
      "GUARDIAN_ROLE",
      "MarketSkipped",
      "PriceRejected",
      "PriceConfidenceRejected",
      "RebasePending",
      "PriceRebased",
      "RoundVoided",
      "RoundLocked",
      "RoundClosed",
      "BoundaryExecuted",
      "PythFeePaid",
      "InsufficientPythFee",
      "RefundFailed",
    ],
  },
  predictionMarketLensAbi: {
    path: "PredictionMarketLens.sol/PredictionMarketLens.json",
    names: ["market", "getParams", "getMarketIds", "getMarket", "getRound"],
  },
  pythBoundaryReaderAbi: {
    path: "PythBoundaryReader.sol/PythBoundaryReader.json",
    names: ["updateFee", "pyth"],
  },
};

let body =
  "// Minimal ABI of the Erevor contracts: only the functions, events and errors the keeper uses.\n" +
  "// Generated by scripts/sync-abi.mjs from the contract build output. Do not edit by hand.\n\n";
for (const [name, { path, names }] of Object.entries(pick)) {
  const { abi } = JSON.parse(readFileSync(join(out, path), "utf8"));
  const items = abi.filter((x) => names.includes(x.name));
  const missing = names.filter((n) => !items.some((x) => x.name === n));
  if (missing.length > 0) throw new Error(`${path}: missing ${missing.join(", ")}`);
  body += `export const ${name} = ${JSON.stringify(items, null, 2)} as const;\n\n`;
}
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "abi.ts");
writeFileSync(target, body);
console.log("wrote", target);
